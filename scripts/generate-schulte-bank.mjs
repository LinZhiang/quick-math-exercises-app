function assertBank() {
  if (IDIOMS.length !== 100) throw new Error(`成语应为 100，实际 ${IDIOMS.length}`)
  if (WORDS.length !== 100) throw new Error(`词语应为 100，实际 ${WORDS.length}`)
  const seen = new Set()
  for (const [w] of [...IDIOMS, ...WORDS]) {
    if (!w || /[^\u4e00-\u9fff]/.test(w)) throw new Error(`非法词条: ${w}`)
    if (w.length < 2 || w.length > 8) throw new Error(`词长异常: ${w}`)
    if (seen.has(w)) throw new Error(`重复: ${w}`)
    seen.add(w)
  }
}

assertBank()

const items = [
  ...IDIOMS.map(([word, meaning], i) => ({
    key: `idiom-${String(i + 1).padStart(3, '0')}`,
    kind: 'idiom',
    word,
    meaning,
  })),
  ...WORDS.map(([word, meaning], i) => ({
    key: `word-${String(i + 1).padStart(3, '0')}`,
    kind: 'word',
    word,
    meaning,
  })),
]

const body = items
  .map(
    (it) =>
      `  { key: ${JSON.stringify(it.key)}, kind: ${JSON.stringify(it.kind)}, word: ${JSON.stringify(it.word)}, meaning: ${JSON.stringify(it.meaning)} },`,
  )
  .join('\n')

