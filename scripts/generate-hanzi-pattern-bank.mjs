// Expand to 500: permute order for equal-type items + rotate distractors
function permute4(arr) {
  // generate a few distinct orders
  const [a, b, c, d] = arr
  return [
    [a, b, c, d],
    [d, c, b, a],
    [a, c, b, d],
    [b, a, d, c],
    [c, d, a, b],
    [b, d, a, c],
  ]
}

function stemOf(chars) {
  return `下列汉字：${chars.join('　')}\n其规律是？`
}

function buildItems() {
  /** @type {any[]} */
  const raw = []
  const seenStem = new Set()

  function pushItem(chars, correct, tip, extraDist) {
    const c = /** @type {[string,string,string,string]} */ (chars)
    if (c.length !== 4 || c.some((x) => !x || x.length !== 1)) return
    if (new Set(c).size !== 4) return
    const stem = stemOf(c)
    if (seenStem.has(stem)) return
    seenStem.add(stem)
    raw.push({
      difficulty: 'normal',
      stem,
      correct,
      distractors: distractorsFor(correct, extraDist),
      explanation: [`汉字：${c.join('、')}`, `规律：${correct}`, tip ? `说明：${tip}` : '']
        .filter(Boolean)
        .join('\n'),
      chars: c,
      tip,
    })
  }

  // First pass: seeds as-is
  for (const s of SEEDS) pushItem(s.chars, s.correct, s.tip, s.extraDist)

  const strokePools = {
    2: ['二', '十', '丁', '七', '人', '八', '入', '几', '九', '了'],
    3: ['三', '干', '于', '下', '土', '士', '工', '才', '口', '山', '巾', '千', '大', '丈', '小', '上', '女', '子', '也', '飞'],
    4: ['王', '天', '夫', '井', '木', '不', '太', '犬', '日', '曰', '中', '水', '月', '火', '文', '方', '牛', '午', '手', '毛', '五', '开'],
    5: ['正', '甘', '生', '用', '古', '可', '右', '石', '本', '术', '未', '末', '申', '甲', '电', '田', '白', '皮', '目', '且'],
    6: ['合', '同', '名', '各', '安', '字', '守', '宅', '红', '纤', '约', '级', '军', '农', '冰', '决', '光', '先', '共', '色'],
    7: ['我', '找', '成', '或', '来', '求', '更', '束', '里', '困', '园', '围', '身', '近', '返', '这', '别', '利', '否', '位'],
    8: ['国', '固', '图', '困', '金', '命', '念', '贪', '青', '表', '事', '雨', '和', '知', '的', '到', '使', '例', '供', '依'],
  }
  for (const [n, pool] of Object.entries(strokePools)) {
    for (let i = 0; i + 3 < pool.length; i++) {
      pushItem([pool[i], pool[i + 1], pool[i + 2], pool[i + 3]], '笔画数相等', `均为 ${n} 画`)
    }
    // 间隔取样，增加不同四元组
    for (let i = 0; i + 9 < pool.length; i++) {
      pushItem([pool[i], pool[i + 3], pool[i + 6], pool[i + 9]], '笔画数相等', `均为 ${n} 画`)
    }
  }

  function categoryOf(correct) {
    if (correct.startsWith('都包含')) return 'contain'
    if (correct.includes('笔画数')) return 'stroke'
    if (correct.includes('交叉')) return 'cross'
    if (correct.includes('封闭区域个数')) return 'enclose-count'
    if (correct.includes('不相连')) return 'parts'
    if (correct.includes('结构')) return 'struct'
    if (correct.includes('对称')) return 'sym'
    if (correct.includes('封闭区域') || correct.includes('开放')) return 'open-closed'
    return 'other'
  }

  function countCat(cat) {
    return raw.filter((x) => categoryOf(x.correct) === cat).length
  }

  // 优先扩展非「包含」类：相等型可打乱顺序；序列型只做循环移位（保持相对增减方向时用逆序已在种子里）
  const expandOrder = ['stroke', 'cross', 'enclose-count', 'parts', 'struct', 'sym', 'open-closed', 'contain']
  const caps = {
    stroke: 90,
    cross: 55,
    'enclose-count': 70,
    parts: 55,
    struct: 70,
    sym: 50,
    'open-closed': 45,
    contain: 70,
  }

  for (const cat of expandOrder) {
    const seeds = SEEDS.filter((s) => categoryOf(s.correct) === cat)
    for (const s of seeds) {
      if (countCat(cat) >= caps[cat]) break
      // 累加/累减顺序不可打乱（逆序种子已单独收录）
      if (s.correct.includes('累加') || s.correct.includes('累减')) continue
      const orders = permute4(s.chars).slice(1)
      for (const p of orders) {
        if (countCat(cat) >= caps[cat]) break
        pushItem(p, s.correct, s.tip, s.extraDist)
      }
    }
  }

  // 填满 500：按缺口继续轮换
  while (raw.length < 500) {
    let added = false
    for (const cat of expandOrder) {
      if (raw.length >= 500) break
      const seeds = SEEDS.filter((s) => categoryOf(s.correct) === cat)
      for (const s of seeds) {
        if (raw.length >= 500) break
        const before = raw.length
        const rot = [s.chars[2], s.chars[3], s.chars[0], s.chars[1]]
        // 序列题：仅当仍保持单调时可加入；累加/累减不乱序填充
        if (s.correct.includes('累加') || s.correct.includes('累减')) continue
        pushItem(rot, s.correct, s.tip, s.extraDist)
        if (raw.length > before) added = true
      }
    }
    if (!added) break
  }

  if (raw.length < 500) {
    throw new Error(`种子不足，仅生成 ${raw.length} 题，需要 500`)
  }

  return raw.slice(0, 500).map((item, idx) => {
    const n = String(idx + 1).padStart(3, '0')
    return {
      difficulty: 'normal',
      stem: item.stem,
      correct: item.correct,
      distractors: item.distractors,
      explanation: item.explanation,
      key: `hanzi-pattern:${n}`,
      chars: item.chars,
    }
  })
}

const items = buildItems()
if (items.length !== 500) throw new Error(`expected 500, got ${items.length}`)
const keys = new Set(items.map((x) => x.key))
if (keys.size !== 500) throw new Error('duplicate keys')

const counts = {}
for (const it of items) {
  const k = it.correct.startsWith('都包含') ? '都包含某成分' : it.correct
  counts[k] = (counts[k] || 0) + 1
}
console.log('pattern counts:', counts)

