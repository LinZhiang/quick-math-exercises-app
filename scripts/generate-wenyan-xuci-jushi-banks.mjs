import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))

function esc(s) {
  return String(s).replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$/g, '\\$')
}

function writeBank(filePath, typeImport, typeName, exportName, items, header) {
  const body = items
    .map(
      (it) => `  {
    difficulty: 'normal',
    stem: \`${esc(it.stem)}\`,
    correct: ${JSON.stringify(it.correct)},
    distractors: ${JSON.stringify(it.distractors)},
    explanation: \`${esc(it.explanation)}\`,
    key: ${JSON.stringify(it.key)},
  }`,
    )
    .join(',\n')
  fs.writeFileSync(
    filePath,
    `${header}
import type { ${typeName} } from '@/utils/${typeImport}'

export const ${exportName}: ${typeName}[] = [
${body},
]
`,
    'utf8',
  )
  console.log('wrote', path.basename(filePath), items.length)
}

