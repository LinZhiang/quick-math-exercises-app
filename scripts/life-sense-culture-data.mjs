export function getCultureQaByDifficulty(diff) {
  return {
    music: ANCIENT_MUSIC_QA[diff] || [],
    opera: ANCIENT_OPERA_QA[diff] || [],
    tech: ANCIENT_TECH_QA[diff] || [],
  }
}

function assertThirty(name, bag) {
  for (const diff of /** @type {const} */ (['easy', 'normal', 'hard'])) {
    const n = (bag[diff] || []).length
    if (n !== 30) {
      throw new Error(`${name} ${diff} 应为 30 题，实际 ${n}`)
    }
  }
}

