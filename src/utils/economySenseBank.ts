import type { EconomySenseBankItem } from '@/utils/economySenseBankTypes'

function item(
  term: string,
  correct: string,
  distractors: string[],
  example: string,
  tip?: string,
): EconomySenseBankItem {
  const explanation = [
    correct.trim(),
    `举例：${example.trim()}`,
    tip ? `速记：${tip.trim()}` : '',
  ]
    .filter(Boolean)
    .join('\n')
  return {
    difficulty: 'normal',
    stem: `什么是${term}？`,
    correct: correct.trim(),
    distractors: distractors.map((d) => d.trim()).filter(Boolean),
    explanation,
    key: `economy-sense:${term}`,
  }
}

