function distractorsFor(cat: Cat, correct: string): string[] {
  const pool = DISTRACTOR_POOL[cat].filter((x) => x !== correct)
  const extras = [
    '授予官职',
    '罢免官职',
    '提升官职',
    '降低官职',
    '调任',
    '代理官职',
    '辞官退休',
    '拜访',
    '告辞',
    '责备',
    '劝说',
    '称赞',
    '憎恨',
    '到……去',
    '离开',
    '死亡',
    '刑罚',
    '不久、一会儿',
    '曾经',
    '等到',
  ].filter((x) => x !== correct && !pool.includes(x))
  return [...pool, ...extras].slice(0, 5)
}

function item(
  key: string,
  word: string,
  sentence: string,
  correct: string,
  cat: Cat,
  tip?: string,
): WenyanShiciBankItem {
  const stem = `「${word}」在「${sentence}」中的含义是？`
  const explanation = [
    `类别：${cat}`,
    `例句：${sentence}`,
    `此处「${word}」意为：${correct}。`,
    tip ? `速记：${tip}` : '',
  ]
    .filter(Boolean)
    .join('\n')
  return {
    difficulty: 'normal',
    stem,
    correct,
    distractors: distractorsFor(cat, correct),
    explanation,
    key: `wenyan-shici:${key}`,
  }
}

